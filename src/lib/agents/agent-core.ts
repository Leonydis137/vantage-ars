/*
 * Agent core: small runtime for executing actions with dry-run and audit logging.
 * src/lib/agents/agent-core.ts
 */
import { randomUUID } from 'crypto';
import type { AgentAction, AgentDecision, AgentContext } from './types';

export class AgentCore {
  id: string;
  callsign: string;
  title: string;
  ctx: AgentContext;

  constructor(id: string, callsign: string, title: string, ctx: AgentContext = {}) {
    this.id = id;
    this.callsign = callsign;
    this.title = title;
    this.ctx = ctx;
  }

  async runAction(action: AgentAction): Promise<AgentDecision> {
    const decisionId = randomUUID();
    const startAt = new Date().toISOString();
    const logger = this.ctx.logger ?? console;
    logger.info(`[Agent:${this.callsign}] runAction`, action.kind, action.id);

    // Produce a proposed decision from action. Real agents should override and call _recordDecision
    const decision: AgentDecision = {
      id: decisionId,
      agentId: this.id,
      actionKind: action.kind,
      title: action.title,
      rationale: `Auto-generated by agent ${this.callsign} for action ${action.id}`,
      status: this.ctx.dryRun ? 'draft' : 'proposed',
      confidence: 0.7,
      reversible: true,
      amountCents: 0,
      evidence: { startAt, inputs: action.inputs },
      createdAt: startAt
    };

    // Audit record: attempt to write to agent_audit_logs if DB available.
    await this._recordAudit(action, decision);

    return decision;
  }

  async _recordAudit(action: AgentAction, decision: AgentDecision) {
    const logger = this.ctx.logger ?? console;
    const db = this.ctx.db;

    // Prepare a minimal audit row payload
    const auditRow = {
      id: decision.id,
      agent_id: this.id,
      action_kind: action.kind,
      title: decision.title,
      inputs_json: JSON.stringify(action.inputs ?? {}),
      output_json: JSON.stringify(decision.evidence ?? {}),
      status: decision.status,
      confidence: decision.confidence ?? null,
      reversible: decision.reversible ? true : false,
      evidence_hash: null,
      created_at: new Date().toISOString()
    };

    if (db && typeof db.exec === 'function') {
      // If scripts/migrate.mjs created a simple sqlite wrapper with exec, try that
      try {
        const sql = `insert into agent_audit_logs(id, agent_id, action_kind, title, inputs_json, output_json, status, confidence, reversible, evidence_hash, created_at) values ($id, $agent_id, $action_kind, $title, $inputs_json, $output_json, $status, $confidence, $reversible, $evidence_hash, $created_at)`;
        await db.exec(sql, auditRow);
        logger.info(`[Agent:${this.callsign}] audit written to DB`);
        return;
      } catch (err) {
        logger.warn('[Agent] DB exec failed, falling back to console log', err);
      }
    }

    // Fallback: log the audit row to logger
    logger.info('[Agent] audit row (no-db)', auditRow);
  }
}
